"""Draft intent signals when an investor's activity arrives (JM2-1134).

The requirement, from the 2026-09-11 escalation: "GET for the Intent Signal generated by Qiko
against the activities of the investors. This should send all available intent signals for all
investors." Generation is Qiko's job and the trigger is activity, not a panel opening a page:
the integrating team has no trigger on their side, only a page that displays what it reads.

Before this, signals were drafted in exactly two places: an explicit POST, and the
single-investor read (which drafts once on demand). Both require somebody to name an investor
first, so the cross-investor feed only ever contained investors who had already been clicked
into. That is the per-investor querying the requirement exists to replace.

Enqueue-on-activity rather than a periodic sweep over every investor, following
channels/digest_scheduler: the event is the moment new evidence exists, so a draft is only ever
paid for on an investor who actually did something. A sweep would redraft unchanged behaviour or
need its own bookkeeping to avoid it.

One environment note. EagerTaskQueue (dev and tests) ignores `defer_by` and runs the job inline,
where it finds an event that just happened and defers without spending. Nothing re-runs it, so
scheduled drafts do not appear in dev: use the per-investor read, which drafts on demand, or the
explicit POST. Non-dev runs arq, which the production config check already enforces, so the
deferral is real there.
"""
from __future__ import annotations

import asyncio
import logging
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Callable, Protocol
from uuid import uuid4

from app.core.config import get_settings
from app.core.tenancy import reset_tenant, set_tenant
from app.modules.ai import usage
from app.modules.joseph_mews.activity import (
    ActivityEvent,
    IntentSignalRequest,
    IntentSignalStore,
    InvestorActivityStore,
    aggregate_activity,
    generate_intent_signals,
    has_signal_worthy_evidence,
)

logger = logging.getLogger(__name__)

TASK_NAME = "draft_jm_intent_signals"
_SOURCE = "joseph_mews.signals"


class TaskQueue(Protocol):
    async def enqueue(self, name: str, *, defer_by: timedelta | None = None,
                      **kwargs) -> object: ...


def draft_window() -> timedelta:
    """How long an investor must be quiet before their activity is drafted.

    A browsing session emits many events; drafting on the first would describe a half-finished
    visit and then be replaced minutes later, paying for both.
    """
    return timedelta(minutes=get_settings().jm_signal_draft_delay_minutes)


@dataclass
class IntentSignalScheduler:
    """Call on_activity from POST /activity."""

    task_queue: TaskQueue
    window: timedelta | None = None

    async def on_activity(self, tenant: str, investor_ref: str) -> None:
        """Enqueue a deferred draft for this investor.

        Never raises. Activity logging is the start of the whole chain, so a queue outage must
        not stop an investor's activity from being recorded: the draft is recoverable, because
        the next event enqueues again, whereas a refused write is gone.
        """
        try:
            await self.task_queue.enqueue(
                TASK_NAME, tenant=tenant, investor_ref=investor_ref,
                defer_by=self.window if self.window is not None else draft_window())
        except Exception:
            logger.warning("could not schedule an intent signal draft; activity still recorded",
                           exc_info=True, extra={"source": _SOURCE, "tenant": tenant})


def _newest(events: list[ActivityEvent]) -> datetime | None:
    stamps = [e.occurred_at for e in events if e.occurred_at is not None]
    return max(stamps) if stamps else None


@dataclass
class IntentSignalDraftWorker:
    """The task function wired into app.tasks.jobs.

    Every branch that returns before `generate` is a model call not made. That is the point:
    this path runs unattended, once per investor per burst of activity, so the cheap checks
    (quiet window, evidence threshold, staleness, spend cap) all come first.
    """

    activity: InvestorActivityStore
    signals: IntentSignalStore
    provider: object | None = None
    cost_guard: object | None = None
    usage_store: object | None = None
    agent_config: dict | None = None
    window: timedelta | None = None
    # Injected so a test can assert the model was never reached. Defaults to the same function
    # the read path uses, so the two cannot drift on what counts as a signal.
    generate: Callable[..., object] = field(default=generate_intent_signals)

    async def run(self, *, tenant: str, investor_ref: str) -> dict:
        events = await self.activity.list_for_investor(tenant, investor_ref)
        if not events:
            return {"ok": True, "skipped": "no activity"}

        window = self.window if self.window is not None else draft_window()
        newest = _newest(events)
        if newest is not None and (datetime.now(timezone.utc) - newest) < window:
            # Still browsing. The next event enqueues another job, so nothing is lost.
            return {"ok": True, "deferred": True}

        aggregated = aggregate_activity(events)
        if not has_signal_worthy_evidence(aggregated):
            # The same judgement the on-demand read applies, so a background draft cannot invent
            # a signal that path would have refused to make.
            return {"ok": True, "skipped": "insufficient evidence"}

        stored = await self.signals.list_for_investor(tenant, investor_ref)
        drafted_at = max((s.generated_at for s in stored if s.generated_at is not None),
                         default=None)
        if drafted_at is not None and newest is not None and drafted_at >= newest:
            # A signal describes current behaviour: identical activity redrafts to the same
            # sentence, and every enqueued event would otherwise pay for it again.
            return {"ok": True, "skipped": "no new activity since the last draft"}

        if self.cost_guard is not None:
            decision = await self.cost_guard.check(tenant)
            if not decision.allowed:
                logger.warning("intent signal draft skipped: AI cost cap reached",
                               extra={"source": _SOURCE, "tenant": tenant})
                return {"ok": False, "skipped": "cost cap reached"}

        result = await self._generate(tenant, investor_ref, aggregated)
        if result is None:
            # generate_intent_signals returns None rather than raising on an unusable response.
            # Storing an empty set would read as "processed, nothing to say", a different claim.
            logger.warning("intent signal draft produced nothing usable",
                           extra={"source": _SOURCE, "tenant": tenant})
            return {"ok": False, "skipped": "generation failed"}

        await self.signals.replace_for_investor(tenant, investor_ref, result.signals)
        return {"ok": True, "drafted": len(result.signals)}

    async def _generate(self, tenant: str, investor_ref: str, aggregated: dict):
        """Run the model call with the tenant bound and its spend accounted for.

        Without the tenant context and usage scope the spend is recorded outside a scope and
        dropped, so this background path would consume tokens that never appear in AI usage or
        count towards the tenant's cap.
        """
        request = IntentSignalRequest(
            requestId=f"scheduled-{uuid4()}", investorRef=investor_ref, activity=aggregated)
        token = set_tenant(tenant)
        try:
            with usage.scope() as events:
                try:
                    return await asyncio.to_thread(
                        self.generate, request, self.provider, self.agent_config)
                finally:
                    await usage.flush(self.usage_store, events)
        finally:
            reset_tenant(token)

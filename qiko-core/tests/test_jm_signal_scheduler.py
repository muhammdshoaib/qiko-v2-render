"""Intent signals are drafted when activity arrives, so the all-investors feed is populated
without anyone opening an investor's own page (JM2-1134).

The requirement, from the 2026-09-11 escalation: "GET for the Intent Signal generated by Qiko
against the activities of the investors. This should send all available intent signals for all
investors." Before this, signals were only ever drafted by an explicit POST or by the
single-investor read, so the cross-investor feed only contained investors somebody had already
clicked into, which is the per-investor querying that requirement exists to replace.
"""
from datetime import datetime, timedelta, timezone

import pytest

from app.modules.joseph_mews.activity import (
    InMemoryIntentSignalStore,
    InMemoryInvestorActivityStore,
    IntentSignal,
    IntentSignalResult,
)
from app.modules.joseph_mews.signal_scheduler import (
    IntentSignalDraftWorker,
    IntentSignalScheduler,
)

TENANT = "joseph-mews"


class RecordingQueue:
    def __init__(self):
        self.calls: list[dict] = []

    async def enqueue(self, name: str, *, defer_by=None, **kwargs):
        self.calls.append({"name": name, "defer_by": defer_by, **kwargs})


class CountingProvider:
    """Stands in for the LLM provider so a test can assert it was never reached. Every skip in
    this worker exists to avoid a model call, so "did not spend" is the actual assertion."""

    def __init__(self):
        self.calls = 0


def _result(signal="Interested in Mayfair", strength="high"):
    return IntentSignalResult(
        requestId="r", signals=[IntentSignal(signal=signal, strength=strength,
                                             evidence="viewed 3 times")])


def _worker(activity, signals, *, generator=None, cost_guard=None, window_minutes=10):
    provider = CountingProvider()

    def _generate(request, _provider, _config=None):
        provider.calls += 1
        return generator(request) if generator else _result()

    worker = IntentSignalDraftWorker(
        activity=activity, signals=signals, provider=provider, cost_guard=cost_guard,
        window=timedelta(minutes=window_minutes), generate=_generate)
    return worker, provider


async def _record(activity, investor_ref, *, count=3, minutes_ago=60,
                  property_name="The Mayfair Residence"):
    """Enough repeated evidence to clear has_signal_worthy_evidence (3 visits to one property)."""
    occurred = datetime.now(timezone.utc) - timedelta(minutes=minutes_ago)
    for _ in range(count):
        await activity.record(TENANT, investor_ref, category="property_visit",
                              label="PropertyDetail", property_name=property_name,
                              location="Mount Street, Mayfair", postcode="W1K 2HQ",
                              occurred_at=occurred)


# --- the scheduler: one deferred job per investor whose activity arrived ----------------------


async def test_activity_schedules_a_deferred_draft_for_that_investor():
    queue = RecordingQueue()
    scheduler = IntentSignalScheduler(task_queue=queue, window=timedelta(minutes=10))

    await scheduler.on_activity(TENANT, "45")

    assert queue.calls == [{"name": "draft_jm_intent_signals", "defer_by": timedelta(minutes=10),
                            "tenant": TENANT, "investor_ref": "45"}]


async def test_a_failing_queue_never_breaks_the_activity_write():
    """Activity logging is the start of the whole chain. Losing one draft is recoverable, since
    the next event enqueues again; refusing to record the investor's activity is not."""
    class BrokenQueue:
        async def enqueue(self, *_a, **_kw):
            raise RuntimeError("redis is down")

    scheduler = IntentSignalScheduler(task_queue=BrokenQueue(), window=timedelta(minutes=10))

    await scheduler.on_activity(TENANT, "45")  # must not raise


# --- the worker: every skip avoids a model call ----------------------------------------------


async def test_drafts_and_stores_so_the_all_investors_feed_returns_the_investor():
    """The requirement itself: an investor nobody has opened individually appears in the
    cross-investor feed."""
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45")
    worker, provider = _worker(activity, signals)

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["drafted"] == 1
    assert provider.calls == 1
    found, total = await signals.search(TENANT)
    assert total == 1
    assert found[0].investor_ref == "45"
    assert found[0].signal == "Interested in Mayfair"


async def test_defers_while_activity_is_still_arriving():
    """Drafting mid-session would describe a half-finished visit and be replaced minutes later.
    The next event re-enqueues, so deferring loses nothing."""
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45", minutes_ago=1)
    worker, provider = _worker(activity, signals, window_minutes=10)

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["deferred"] is True
    assert provider.calls == 0
    assert await signals.list_for_investor(TENANT, "45") == []


async def test_skips_when_evidence_is_below_the_threshold():
    """Same judgement the read path applies, so a background draft cannot invent a signal the
    on-demand read would have refused to make."""
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45", count=1)
    worker, provider = _worker(activity, signals)

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["skipped"] == "insufficient evidence"
    assert provider.calls == 0


async def test_skips_when_nothing_happened_since_the_last_draft():
    """A signal describes current behaviour. Re-drafting identical activity spends model budget
    to produce the same sentence, and every enqueued event would otherwise pay for it again."""
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45")
    worker, provider = _worker(activity, signals)

    await worker.run(tenant=TENANT, investor_ref="45")
    assert provider.calls == 1

    outcome = await worker.run(tenant=TENANT, investor_ref="45")
    assert outcome["skipped"] == "no new activity since the last draft"
    assert provider.calls == 1


async def test_redrafts_once_newer_activity_arrives():
    """Staleness is decided by comparing the newest event against when the last draft was made,
    so a later session redrafts while a replayed older one does not. The window is zeroed here
    because the debounce is a separate concern, asserted above.
    """
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45")
    worker, provider = _worker(activity, signals, window_minutes=0)
    await worker.run(tenant=TENANT, investor_ref="45")

    # A second session, recorded after that draft was stored.
    await _record(activity, "45", count=3, minutes_ago=0, property_name="Marina Heights")
    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["drafted"] == 1
    assert provider.calls == 2
    # Replaced, not appended: one investor must not appear twice with contradictory strengths.
    assert len(await signals.list_for_investor(TENANT, "45")) == 1


async def test_skips_when_the_tenant_is_at_its_ai_spend_cap():
    """A background job must not be the one path that ignores the cap."""
    class Capped:
        async def check(self, _tenant):
            class Decision:
                allowed = False
            return Decision()

    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45")
    worker, provider = _worker(activity, signals, cost_guard=Capped())

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["skipped"] == "cost cap reached"
    assert provider.calls == 0


async def test_stores_nothing_when_the_model_gives_no_usable_result():
    """generate_intent_signals returns None rather than raising on an unusable response. Storing
    an empty set would read as "processed, nothing to say", which is a different claim."""
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45")
    worker, _ = _worker(activity, signals, generator=lambda _r: None)

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["skipped"] == "generation failed"
    assert await signals.list_for_investor(TENANT, "45") == []


async def test_no_activity_at_all_is_not_an_error():
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    worker, provider = _worker(activity, signals)

    outcome = await worker.run(tenant=TENANT, investor_ref="45")

    assert outcome["skipped"] == "no activity"
    assert provider.calls == 0


@pytest.mark.parametrize("count", [3, 5])
async def test_evidence_at_or_above_the_threshold_drafts(count):
    activity, signals = InMemoryInvestorActivityStore(), InMemoryIntentSignalStore()
    await _record(activity, "45", count=count)
    worker, _ = _worker(activity, signals)

    assert (await worker.run(tenant=TENANT, investor_ref="45"))["drafted"] == 1
